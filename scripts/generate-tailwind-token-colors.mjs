import fs from 'node:fs/promises';
import path from 'node:path';

const ROOT = process.cwd();
const TOKENS_CSS_PATH = path.join(ROOT, 'app/assets/css/tokens.css');
const OUTPUT_PATH = path.join(ROOT, 'tailwind.tokens.generated.ts');

function toKebabCase(value) {
  return value
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
    .replace(/_/g, '-')
    .toLowerCase();
}

function splitNameAndScale(value) {
  const match = value.match(/^([A-Za-z]+)(\d+)$/);
  if (!match) return toKebabCase(value);
  return `${toKebabCase(match[1])}-${match[2]}`;
}

function toTailwindTokenKey(rawName) {
  if (rawName.startsWith('primariMode1')) {
    const rest = rawName.slice('primariMode1'.length);
    return `token-${splitNameAndScale(rest)}`;
  }

  if (rawName.startsWith('tokensLightBorderBorder')) {
    const rest = rawName.slice('tokensLightBorderBorder'.length);
    return `token-border-${splitNameAndScale(rest)}`;
  }

  if (rawName.startsWith('tokensLightButtonButton')) {
    const rest = rawName.slice('tokensLightButtonButton'.length);
    return `token-button-${splitNameAndScale(rest)}`;
  }

  if (rawName.startsWith('tokensLightBackgroundBackground')) {
    const rest = rawName.slice('tokensLightBackgroundBackground'.length);
    return `token-background-${splitNameAndScale(rest)}`;
  }

  return `token-${toKebabCase(rawName)}`;
}


function categorizeToken(rawName) {
  // Determina la categoria in base al prefisso del nome
  if (
    rawName.startsWith('primariMode1') ||
    rawName.startsWith('tokensLight')
  ) {
    // Classifica i token specifici
    if (rawName.includes('Border')) return 'border';
    if (rawName.includes('Radius')) return 'borderRadius';
    if (rawName.includes('Button')) return 'button';
    if (rawName.includes('Background')) return 'background';
    if (rawName.includes('Text') || rawName.includes('Typography')) return 'typography';
    if (rawName.includes('Spacing') || rawName.includes('Gap')) return 'spacing';
    if (rawName.includes('Shadow')) return 'boxShadow';
    
    // Default: colori
    return 'colors';
  }
  return 'colors';
}

async function main() {
  const css = await fs.readFile(TOKENS_CSS_PATH, 'utf8');

  const variableMatches = [...css.matchAll(/^\s*--([A-Za-z0-9_-]+)\s*:/gm)];

  // Organizza i token per categoria
  const tokensByCategory = {
    colors: [],
    border: [],
    borderRadius: [],
    button: [],
    background: [],
    typography: [],
    spacing: [],
    boxShadow: []
  };

  variableMatches
    .map((match) => match[1])
    .filter(Boolean)
    .forEach((rawName) => {
      const category = categorizeToken(rawName);
      const key = toTailwindTokenKey(rawName);
      const value = `var(--${rawName})`;
      tokensByCategory[category].push([key, value]);
    });

  // Ordina ogni categoria
  Object.keys(tokensByCategory).forEach((category) => {
    tokensByCategory[category].sort((a, b) => a[0].localeCompare(b[0]));
  });

  // Genera il file TypeScript
  const lines = [
    '// Auto-generated by scripts/generate-tailwind-token-colors.mjs',
    '// Do not edit manually.',
    '// Token categories: colors, border, borderRadius, button, background, typography, spacing, boxShadow',
    ''
  ];

  // Esporta ogni categoria (anche vuota, per mantenere import stabili)
  Object.entries(tokensByCategory).forEach(([category, entries]) => {
    const exportName = `token${category.charAt(0).toUpperCase() + category.slice(1)}`;
    lines.push(`export const ${exportName} = {`);

    for (const [key, value] of entries) {
      lines.push(`  '${key}': '${value}',`);
    }

    lines.push('} as const;');
    lines.push('');
  });

  await fs.writeFile(OUTPUT_PATH, lines.join('\n'), 'utf8');
  
  const totalTokens = Object.values(tokensByCategory).reduce((sum, arr) => sum + arr.length, 0);
  console.log(`✓ Generated ${OUTPUT_PATH}`);
  console.log(`  Total tokens: ${totalTokens}`);
  Object.entries(tokensByCategory).forEach(([cat, entries]) => {
    if (entries.length > 0) {
      console.log(`  - ${cat}: ${entries.length}`);
    }
  });
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
