import fs from 'node:fs/promises';
import path from 'node:path';

const ROOT = process.cwd();
const TOKENS_CSS_PATH = path.join(ROOT, 'app/assets/css/tokens.css');
const OUTPUT_PATH = path.join(ROOT, 'tailwind.tokens.generated.ts');

function toKebabCase(value) {
  return value
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
    .replace(/_/g, '-')
    .toLowerCase();
}

function splitNameAndScale(value) {
  const match = value.match(/^([A-Za-z]+)(\d+)$/);
  if (!match) return toKebabCase(value);
  return `${toKebabCase(match[1])}-${match[2]}`;
}

function toTailwindTokenKey(rawName) {
  if (rawName.startsWith('primariMode1')) {
    const rest = rawName.slice('primariMode1'.length);
    return `token-${splitNameAndScale(rest)}`;
  }

  if (rawName.startsWith('tokensLightBorderBorder')) {
    const rest = rawName.slice('tokensLightBorderBorder'.length);
    return `token-border-${splitNameAndScale(rest)}`;
  }

  if (rawName.startsWith('tokensLightButtonButton')) {
    const rest = rawName.slice('tokensLightButtonButton'.length);
    return `token-button-${splitNameAndScale(rest)}`;
  }

  if (rawName.startsWith('tokensLightBackgroundBackground')) {
    const rest = rawName.slice('tokensLightBackgroundBackground'.length);
    return `token-background-${splitNameAndScale(rest)}`;
  }

  return `token-${toKebabCase(rawName)}`;
}

async function main() {
  const css = await fs.readFile(TOKENS_CSS_PATH, 'utf8');

  const variableMatches = [...css.matchAll(/^\s*--([A-Za-z0-9_-]+)\s*:/gm)];

  const entries = variableMatches
    .map((match) => match[1])
    .filter(Boolean)
    .map((rawName) => {
      const key = toTailwindTokenKey(rawName);
      const value = `var(--${rawName})`;
      return [key, value];
    })
    .sort((a, b) => a[0].localeCompare(b[0]));

  const lines = [
    '// Auto-generated by scripts/generate-tailwind-token-colors.mjs',
    '// Do not edit manually.',
    '',
    'export const tokenColors = {'
  ];

  for (const [key, value] of entries) {
    lines.push(`  '${key}': '${value}',`);
  }

  lines.push('} as const;');
  lines.push('');

  await fs.writeFile(OUTPUT_PATH, lines.join('\n'), 'utf8');
  console.log(`Generated ${OUTPUT_PATH} with ${entries.length} color tokens.`);
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
